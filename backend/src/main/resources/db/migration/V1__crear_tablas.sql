-- MeDiTurno: estructura inicial de la base de datos.
-- Generada a partir del modelo de datos del equipo. Una vez que este script esté en `main`, NO se edita:
-- los cambios van en scripts nuevos (V2, V3, ...). Ver «Base de datos y migraciones» en CLAUDE.md.

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo VARCHAR(255) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    proveedor_acceso VARCHAR(20),
    fecha_creacion TIMESTAMP NOT NULL,
    ultimo_acceso TIMESTAMP,
    cedula VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    telefono VARCHAR(30),
    firebase_uid VARCHAR(128),
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT ck_usuario_proveedor_acceso CHECK (proveedor_acceso IN ('PASSWORD', 'GOOGLE')),
    CONSTRAINT uq_usuario_cedula UNIQUE (cedula),
    CONSTRAINT uq_usuario_firebase_uid UNIQUE (firebase_uid)
);

CREATE TABLE paciente (
    id_usuario BIGINT PRIMARY KEY,
    domicilio VARCHAR(255),
    fecha_alta TIMESTAMP NOT NULL,
    CONSTRAINT fk_paciente_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

CREATE TABLE funcionario (
    id_usuario BIGINT PRIMARY KEY,
    CONSTRAINT fk_funcionario_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

CREATE TABLE medico (
    id_usuario BIGINT PRIMARY KEY,
    matricula VARCHAR(30) NOT NULL,
    CONSTRAINT fk_medico_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT uq_medico_matricula UNIQUE (matricula)
);

CREATE TABLE administrador (
    id_usuario BIGINT PRIMARY KEY,
    CONSTRAINT fk_administrador_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);

CREATE TABLE especialidad (
    codigo VARCHAR(20) PRIMARY KEY,
    requiere_pase BOOLEAN NOT NULL DEFAULT FALSE,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500),
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT uq_especialidad_nombre UNIQUE (nombre),
    CONSTRAINT ck_especialidad_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE consultorio (
    codigo VARCHAR(20) PRIMARY KEY,
    ubicacion VARCHAR(200) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500),
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT ck_consultorio_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

-- Especialidades que atiende cada médico (muchos a muchos)
CREATE TABLE medico_especialidad (
    id_medico BIGINT NOT NULL,
    codigo_especialidad VARCHAR(20) NOT NULL,
    PRIMARY KEY (id_medico, codigo_especialidad),
    CONSTRAINT fk_medico_especialidad_medico FOREIGN KEY (id_medico) REFERENCES medico (id_usuario),
    CONSTRAINT fk_medico_especialidad_especialidad FOREIGN KEY (codigo_especialidad) REFERENCES especialidad (codigo)
);

CREATE TABLE historia_clinica (
    id_historia_clinica BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL,
    antecedentes TEXT,
    fecha_apertura TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP,
    CONSTRAINT fk_historia_clinica_id_paciente FOREIGN KEY (id_paciente) REFERENCES paciente (id_usuario)
);

CREATE INDEX idx_historia_clinica_paciente ON historia_clinica (id_paciente);

CREATE TABLE anuncio (
    id_anuncio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_funcionario BIGINT NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    contenido TEXT NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_publicacion TIMESTAMP,
    fecha_inicio DATE,
    fecha_fin DATE,
    anuncio_estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_anuncio_id_funcionario FOREIGN KEY (id_funcionario) REFERENCES funcionario (id_usuario),
    CONSTRAINT ck_anuncio_anuncio_estado CHECK (anuncio_estado IN ('PUBLICADO', 'ELIMINADO'))
);

CREATE TABLE imagen_anuncio (
    id_imagen_anuncio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_anuncio BIGINT NOT NULL,
    imagen VARCHAR(500) NOT NULL,
    orden INTEGER NOT NULL DEFAULT 0,
    nombre_archivo VARCHAR(255),
    tipo_contenido VARCHAR(100),
    texto_alternativo VARCHAR(255),
    CONSTRAINT fk_imagen_anuncio_id_anuncio FOREIGN KEY (id_anuncio) REFERENCES anuncio (id_anuncio)
);

CREATE TABLE turno_semanal (
    id_turno_semanal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medico BIGINT NOT NULL,
    codigo_especialidad VARCHAR(20) NOT NULL,
    codigo_consultorio VARCHAR(20) NOT NULL,
    dia VARCHAR(10) NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    cupo_maximo INTEGER NOT NULL,
    vigente_desde DATE NOT NULL,
    vigente_hasta DATE,
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_turno_semanal_id_medico FOREIGN KEY (id_medico) REFERENCES medico (id_usuario),
    CONSTRAINT fk_turno_semanal_codigo_especialidad FOREIGN KEY (codigo_especialidad) REFERENCES especialidad (codigo),
    CONSTRAINT fk_turno_semanal_codigo_consultorio FOREIGN KEY (codigo_consultorio) REFERENCES consultorio (codigo),
    CONSTRAINT ck_turno_semanal_dia CHECK (dia IN ('LUNES', 'MARTES', 'MIERCOLES', 'JUEVES', 'VIERNES', 'SABADO', 'DOMINGO')),
    CONSTRAINT ck_turno_semanal_cupo_maximo CHECK (cupo_maximo >= 1),
    CONSTRAINT ck_turno_semanal_estado CHECK (estado IN ('ACTIVO', 'SUSPENDIDO'))
);

ALTER TABLE turno_semanal ADD CONSTRAINT ck_turno_semanal_horario CHECK (hora_fin > hora_inicio);
CREATE INDEX idx_turno_semanal_especialidad ON turno_semanal (codigo_especialidad);
CREATE INDEX idx_turno_semanal_medico ON turno_semanal (id_medico);
CREATE INDEX idx_turno_semanal_consultorio ON turno_semanal (codigo_consultorio, dia);

CREATE TABLE ocurrencia_turno (
    id_ocurrencia_turno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turno_semanal BIGINT NOT NULL,
    fecha DATE NOT NULL,
    cupos INTEGER NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    ocurrencia_turno_estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_ocurrencia_turno_id_turno_semanal FOREIGN KEY (id_turno_semanal) REFERENCES turno_semanal (id_turno_semanal),
    CONSTRAINT ck_ocurrencia_turno_cupos CHECK (cupos >= 1),
    CONSTRAINT ck_ocurrencia_turno_ocurrencia_turno_estado CHECK (ocurrencia_turno_estado IN ('HABILITADA', 'SUSPENDIDA', 'FINALIZADA'))
);

ALTER TABLE ocurrencia_turno ADD CONSTRAINT uq_ocurrencia_turno_fecha UNIQUE (id_turno_semanal, fecha);
ALTER TABLE ocurrencia_turno ADD CONSTRAINT ck_ocurrencia_turno_horario CHECK (hora_fin > hora_inicio);
CREATE INDEX idx_ocurrencia_turno_fecha ON ocurrencia_turno (fecha);

CREATE TABLE suspension_turno (
    id_suspension_turno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turno_semanal BIGINT NOT NULL,
    id_funcionario BIGINT NOT NULL,
    periodo VARCHAR(100),
    motivo VARCHAR(500),
    suspension_tipo VARCHAR(20) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    fecha_registro TIMESTAMP NOT NULL,
    fecha_rehabilitacion TIMESTAMP,
    CONSTRAINT fk_suspension_turno_id_turno_semanal FOREIGN KEY (id_turno_semanal) REFERENCES turno_semanal (id_turno_semanal),
    CONSTRAINT fk_suspension_turno_id_funcionario FOREIGN KEY (id_funcionario) REFERENCES funcionario (id_usuario),
    CONSTRAINT ck_suspension_turno_suspension_tipo CHECK (suspension_tipo IN ('TEMPORAL', 'PERMANENTE'))
);

ALTER TABLE suspension_turno ADD CONSTRAINT ck_suspension_turno_fin CHECK (suspension_tipo = 'PERMANENTE' OR fecha_fin IS NOT NULL);
CREATE INDEX idx_suspension_turno_turno ON suspension_turno (id_turno_semanal);

CREATE TABLE reserva (
    id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL,
    id_ocurrencia_turno BIGINT NOT NULL,
    id_funcionario BIGINT,
    id_administrador BIGINT,
    numero INTEGER NOT NULL,
    reserva_estado VARCHAR(20) NOT NULL,
    fecha_reserva TIMESTAMP NOT NULL,
    fecha_cancelacion TIMESTAMP,
    motivo_cancelacion VARCHAR(500),
    id_pase BIGINT,
    CONSTRAINT fk_reserva_id_paciente FOREIGN KEY (id_paciente) REFERENCES paciente (id_usuario),
    CONSTRAINT fk_reserva_id_ocurrencia_turno FOREIGN KEY (id_ocurrencia_turno) REFERENCES ocurrencia_turno (id_ocurrencia_turno),
    CONSTRAINT fk_reserva_id_funcionario FOREIGN KEY (id_funcionario) REFERENCES funcionario (id_usuario),
    CONSTRAINT fk_reserva_id_administrador FOREIGN KEY (id_administrador) REFERENCES administrador (id_usuario),
    CONSTRAINT ck_reserva_numero CHECK (numero >= 1),
    CONSTRAINT ck_reserva_reserva_estado CHECK (reserva_estado IN ('VIGENTE', 'ORDEN_EMITIDA', 'ATENDIDA', 'CANCELADA', 'ANULADA', 'VENCIDA'))
);

CREATE INDEX idx_reserva_paciente ON reserva (id_paciente);
CREATE INDEX idx_reserva_ocurrencia ON reserva (id_ocurrencia_turno);
-- Un número de una ocurrencia solo puede estar tomado por una reserva que lo conserve (las canceladas y anuladas lo liberan).
CREATE UNIQUE INDEX uq_reserva_numero_ocupado ON reserva (id_ocurrencia_turno, numero)
    WHERE reserva_estado NOT IN ('CANCELADA', 'ANULADA');

CREATE TABLE orden (
    numero_orden BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL,
    id_funcionario BIGINT NOT NULL,
    id_reserva BIGINT NOT NULL,
    fecha_emision TIMESTAMP NOT NULL,
    orden_estado VARCHAR(20) NOT NULL,
    datos_emision TEXT,
    CONSTRAINT fk_orden_id_paciente FOREIGN KEY (id_paciente) REFERENCES paciente (id_usuario),
    CONSTRAINT fk_orden_id_funcionario FOREIGN KEY (id_funcionario) REFERENCES funcionario (id_usuario),
    CONSTRAINT uq_orden_id_reserva UNIQUE (id_reserva),
    CONSTRAINT fk_orden_id_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
    CONSTRAINT ck_orden_orden_estado CHECK (orden_estado IN ('EMITIDA', 'UTILIZADA'))
);

CREATE TABLE consulta (
    id_consulta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL,
    id_medico BIGINT NOT NULL,
    id_historia_clinica BIGINT NOT NULL,
    id_reserva BIGINT NOT NULL,
    numero_orden BIGINT NOT NULL,
    fecha TIMESTAMP NOT NULL,
    motivo TEXT NOT NULL,
    observaciones TEXT,
    indicaciones TEXT,
    fecha_registro TIMESTAMP NOT NULL,
    CONSTRAINT fk_consulta_id_paciente FOREIGN KEY (id_paciente) REFERENCES paciente (id_usuario),
    CONSTRAINT fk_consulta_id_medico FOREIGN KEY (id_medico) REFERENCES medico (id_usuario),
    CONSTRAINT fk_consulta_id_historia_clinica FOREIGN KEY (id_historia_clinica) REFERENCES historia_clinica (id_historia_clinica),
    CONSTRAINT uq_consulta_id_reserva UNIQUE (id_reserva),
    CONSTRAINT fk_consulta_id_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
    CONSTRAINT uq_consulta_numero_orden UNIQUE (numero_orden),
    CONSTRAINT fk_consulta_numero_orden FOREIGN KEY (numero_orden) REFERENCES orden (numero_orden)
);

CREATE INDEX idx_consulta_paciente ON consulta (id_paciente);
CREATE INDEX idx_consulta_medico ON consulta (id_medico);

CREATE TABLE pase (
    id_pase BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL,
    id_consulta BIGINT NOT NULL,
    especialidad_origen VARCHAR(20) NOT NULL,
    especialidad_destino VARCHAR(20) NOT NULL,
    fecha_emision TIMESTAMP NOT NULL,
    pase_estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_pase_id_paciente FOREIGN KEY (id_paciente) REFERENCES paciente (id_usuario),
    CONSTRAINT fk_pase_id_consulta FOREIGN KEY (id_consulta) REFERENCES consulta (id_consulta),
    CONSTRAINT fk_pase_especialidad_origen FOREIGN KEY (especialidad_origen) REFERENCES especialidad (codigo),
    CONSTRAINT fk_pase_especialidad_destino FOREIGN KEY (especialidad_destino) REFERENCES especialidad (codigo),
    CONSTRAINT ck_pase_pase_estado CHECK (pase_estado IN ('VIGENTE', 'USADO', 'VENCIDO'))
);

CREATE INDEX idx_pase_paciente ON pase (id_paciente, especialidad_destino);

-- Reserva y Pase se referencian entre sí (la reserva usa un pase, y el pase nace de una consulta de otra reserva),
-- por eso esta clave foránea se agrega después de crear las dos tablas.
ALTER TABLE reserva ADD CONSTRAINT fk_reserva_id_pase FOREIGN KEY (id_pase) REFERENCES pase (id_pase);

CREATE TABLE notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_reserva BIGINT,
    id_consulta BIGINT,
    numero_orden BIGINT,
    fecha TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    mensaje VARCHAR(1000) NOT NULL,
    canal VARCHAR(20) NOT NULL,
    fecha_envio TIMESTAMP,
    CONSTRAINT fk_notificacion_id_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_notificacion_id_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
    CONSTRAINT fk_notificacion_id_consulta FOREIGN KEY (id_consulta) REFERENCES consulta (id_consulta),
    CONSTRAINT fk_notificacion_numero_orden FOREIGN KEY (numero_orden) REFERENCES orden (numero_orden),
    CONSTRAINT ck_notificacion_estado CHECK (estado IN ('PENDIENTE', 'ENVIADA', 'FALLIDA', 'LEIDA')),
    CONSTRAINT ck_notificacion_tipo CHECK (tipo IN ('RECORDATORIO_CONSULTA', 'SUSPENSION_TURNO', 'CONSULTA_REGISTRADA')),
    CONSTRAINT ck_notificacion_canal CHECK (canal IN ('EMAIL', 'PUSH', 'APLICACION'))
);

CREATE INDEX idx_notificacion_usuario ON notificacion (id_usuario);

CREATE TABLE token_dispositivo (
    id_token_dispositivo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    token VARCHAR(512) NOT NULL,
    fecha_registro TIMESTAMP NOT NULL,
    CONSTRAINT fk_token_dispositivo_id_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT uq_token_dispositivo_token UNIQUE (token)
);

CREATE INDEX idx_token_dispositivo_usuario ON token_dispositivo (id_usuario);
